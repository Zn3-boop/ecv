def _find_app_path(name: str) -> str | None:
    """根据应用名查找 Windows 绝对路径（使用软件索引，支持模糊匹配）"""
    # 优先使用软件索引（支持模糊匹配、别名、系统内置工具）
    entry = find_software(name)
    if entry and entry.exe_path and os.path.exists(entry.exe_path):
        return entry.exe_path
    
    # 兜底：传统注册表 App Paths 查找
    exe_name = name if name.endswith('.exe') else f"{name}.exe"
    
    try:
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                          r"SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths") as key:
            try:
                with winreg.OpenKey(key, exe_name) as app_key:
                    path, _ = winreg.QueryValueEx(app_key, None)
                    if path and os.path.exists(path):
                        return path
            except FileNotFoundError:
                pass
    except Exception:
        pass
    
    return None


def _resolve_launch_path(args: dict[str, Any]) -> dict[str, Any]:
    """对 app:launch 参数进行路径解析，返回新的 args"""
    path = args.get("path", "")
    if not path:
        return args
    
    # 已经是绝对路径且存在 -> 直接放行
    if os.path.isabs(path) and os.path.exists(path):
        return args
    
    # 相对路径/文件名 -> 使用软件索引查找绝对路径
    if not os.path.isabs(path):
        found = _find_app_path(path)
        if found:
            new_args = dict(args)
            new_args["path"] = found
            return new_args
    
    # 绝对路径但文件不存在 -> 尝试按文件名重新查找
    if os.path.isabs(path) and not os.path.exists(path):
        found = _find_app_path(os.path.basename(path))
        if found:
            new_args = dict(args)
            new_args["path"] = found
            return new_args
    
    return args


